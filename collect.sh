#!/usr/bin/env bash
#
# collect.sh - copies the setup of every running Docker app into this repo.
#
# For each running container it finds the docker-compose project it came from
# and copies the compose file plus small source/config files (Dockerfile, .py,
# .yaml, .html...). It never copies .env files, databases, media, logins or
# app data. For every .env it finds, it writes a .env.example with the values
# blanked out. At the end it scans everything for passwords left in plain text.
#
# Run it again any time you change your server; Git will show what changed.

set -euo pipefail

REPO="$(cd "$(dirname "$0")" && pwd)"
APPS="$REPO/apps"
mkdir -p "$APPS"

# Folders that hold app data, media or logins: never copied
SKIP_DIRS=(.git .venv venv node_modules __pycache__ data config cache music media
           gluetun incomplete downloads filebrowser-data jellyfin logs backups etc-pihole etc-dnsmasq.d
           output vw-data pgdata postgres-data)   # output = server-map's page (shows the public IP)

# Compose projects that have their own GitHub repo: not copied here
SKIP_PROJECTS=(flight-tracker)

# Only these kinds of files are copied, and only if smaller than 200 KB
KEEP_NAMES=(Dockerfile Caddyfile '*.yml' '*.yaml' '*.py' '*.html' '*.css' '*.js' '*.svg'
            '*.md' '*.txt' '*.toml' '*.conf' '*.sh' '.env.example' '.dockerignore' '.gitignore')

declare -A seen=()
not_compose=()

for container in $(docker ps --format '{{.Names}}'); do
  project=$(docker inspect "$container" --format '{{index .Config.Labels "com.docker.compose.project"}}')
  workdir=$(docker inspect "$container" --format '{{index .Config.Labels "com.docker.compose.project.working_dir"}}')

  if [[ -z "$project" || -z "$workdir" ]]; then
    not_compose+=("$container")
    continue
  fi
  [[ -n "${seen[$project]:-}" ]] && continue   # several containers, one project (e.g. torrent)
  seen[$project]=1
  if [[ " ${SKIP_PROJECTS[*]} " == *" $project "* ]]; then
    echo "-- $project  (has its own repo, skipped)"
    continue
  fi

  dest="$APPS/$project"
  mkdir -p "$dest"
  echo "-> $project  (from $workdir)"

  # Build the find command: skip data folders, keep only small config/code files
  prune=()
  for d in "${SKIP_DIRS[@]}"; do prune+=(-name "$d" -o); done
  names=()
  for n in "${KEEP_NAMES[@]}"; do names+=(-name "$n" -o); done

  (cd "$workdir" && find . -maxdepth 4 \
      \( -type d \( "${prune[@]::${#prune[@]}-1}" \) -prune \) -o \
      \( -type f \( "${names[@]::${#names[@]}-1}" \) -size -200k -print \)) |
  while read -r file; do
    mkdir -p "$dest/$(dirname "$file")"
    cp "$workdir/$file" "$dest/$file"
  done

  # .env holds secrets: publish only the variable names
  if [[ -f "$workdir/.env" ]]; then
    sed -E 's/^([A-Za-z_][A-Za-z0-9_]*)=.*/\1=/' "$workdir/.env" > "$dest/.env.example"
    echo "   wrote .env.example (values removed)"
  fi
done

# Inventory of what runs on the server (no IP addresses, just ports)
{
  echo "# What's running"
  echo
  echo "Generated by collect.sh on $(date +%Y-%m-%d)."
  echo
  echo "| Container | Image | Ports |"
  echo "|---|---|---|"
  docker ps --format '{{.Names}}|{{.Image}}|{{.Ports}}' | sort |
    sed -E 's/0\.0\.0\.0://g; s/\[::\]:[0-9]+->[0-9]+\/(tcp|udp),? ?//g; s/, *$//' |
    awk -F'|' '{printf "| %s | `%s` | %s |\n", $1, $2, $3}'
} > "$APPS/INVENTORY.md"
echo "-> wrote apps/INVENTORY.md"

if (( ${#not_compose[@]} )); then
  echo
  echo "Not started with docker compose (nothing copied):"
  printf '   %s\n' "${not_compose[@]}"
fi

# Look for secrets written in plain text: a password/token/key followed by a
# real value (not empty, and not a ${VARIABLE} reference)
echo
echo "Checking for secrets..."
# (lines that are only a comment, starting with #, are ignored)
hits=$(grep -rniE --include='*.yml' --include='*.yaml' --include='*.conf' --include='*.toml' \
     --include='*.sh' --include='*.env' --include='Caddyfile' \
     '(pass(word|wd)?|secret|token|api[_-]?key|private[_-]?key|credential|pwhash|hash)[A-Za-z0-9_]*["'"'"']?[[:space:]]*[:=][[:space:]]*["'"'"']?[^[:space:]$"'"'"'{}]' \
     "$APPS" | grep -vE '^[^:]+:[0-9]+:[[:space:]]*#' || true)
if [[ -n "$hits" ]]; then
  echo "$hits"
  echo
  echo "!! Possible secrets above. Move them into that app's .env file and use \${NAME}"
  echo "!! in the compose file instead, then run collect.sh again. Do NOT commit yet."
  exit 1
fi
echo "No secrets found. Review with: git status && git diff"
